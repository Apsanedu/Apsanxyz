(() => {
  // <stdin>
  console.log("This site was generated by Hugo.");
  var toggleButton = document.getElementById("toggleButton");
  var imageContainer = document.getElementById("imageContainer");
  var magicalImage = document.getElementById("magicalImage");
  var isImageVisible = false;
  toggleButton.addEventListener("click", () => {
    if (!isImageVisible) {
      imageContainer.style.display = "block";
      setTimeout(() => {
        magicalImage.style.opacity = "1";
        magicalImage.style.filter = "grayscale(0%)";
        magicalImage.classList.add("reveal");
      }, 50);
      toggleButton.textContent = "Hide picture";
    } else {
      magicalImage.style.opacity = "0";
      magicalImage.style.filter = "grayscale(100%)";
      magicalImage.classList.remove("reveal");
      setTimeout(() => {
        imageContainer.style.display = "none";
      }, 1e3);
      toggleButton.textContent = "Show picture";
    }
    isImageVisible = !isImageVisible;
  });
})();
